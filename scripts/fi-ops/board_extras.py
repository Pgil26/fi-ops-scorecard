def build_fleet(day):
    cfg = json.load(open(os.path.join(DATA, "fleet.config.json")))
    regions, van_locs = parse_regions()
    files = sorted(f for f in glob.glob("/workspace/geotab-daily-start-end-local-*.csv") if f[-14:-4] <= day)
    files = files[-cfg["lookbackWeekdays"]:]
    status = "ok" if files and files[-1][-14:-4] == day else "pending"
    dev = {}
    for f in files:
        for r in csv.DictReader(open(f)):
            num, _, name = r["Device"].partition(" - ")
            x = dev.setdefault(num, dict(device=num, name=name, zone=r["Zone short"], days=0, activeDays=0, trips=0, miles=0.0, lastActive=None, dayActive=None))
            x["days"] += 1; t = int(r["Trip Count"] or 0)
            if t > 0:
                x["activeDays"] += 1; x["trips"] += t; x["miles"] += float(r["Total Miles"] or 0); x["lastActive"] = r["Date"]
            if r["Date"] == day: x["dayActive"] = t > 0
    locs, _ = parse_ops(); names = {l["id"]: l["name"] for l in locs}
    corp = [lid for lid, reg in regions.items() if reg != "Franchisees"]
    rows = []
    for num, x in sorted(dev.items()):
        loc = cfg["deviceLocations"].get(num) or van_locs.get(norm(x["name"]))
        flags = []
        if not loc: flags.append("No location tag")
        if re.search(r"non ?active|parked", x["name"], re.I): flags.append("Device name says not in service")
        if x["activeDays"] and re.search(r"non ?active|parked", x["name"], re.I): flags.append(f"Still driving: {x['activeDays']} of {x['days']} days active")
        if x["activeDays"] <= max(1, x["days"] // 5): flags.append(f"Low use: {x['activeDays']} of {x['days']} days active")
        x["miles"] = round(x["miles"], 1)
        rows.append(dict(**x, locationId=loc, locationName=names.get(loc), region=regions.get(loc, "Unassigned") if loc else "Unassigned", flags=flags))
    per_loc = collections.Counter(r["locationId"] for r in rows if r["locationId"])
    for r in rows:
        if r["locationId"] and per_loc[r["locationId"]] > 1: r["flags"].append(f"{per_loc[r['locationId']]} devices tagged to {r['locationName']}")
    no_dev = [dict(id=lid, name=names.get(lid, lid), region=regions[lid]) for lid in corp if lid not in per_loc]
    out = dict(day=day, dayLabel=d(day).strftime("%a %b %-d"), status=status, window=dict(first=files[0][-14:-4] if files else None, last=files[-1][-14:-4] if files else None, files=len(files)),
               tracked=len(rows), fleetTotalEstimate=cfg["fleetTotalEstimate"], fleetSource=cfg["fleetSource"],
               untracked=(cfg["fleetTotalEstimate"] - len(rows)) if cfg["fleetTotalEstimate"] else None,
               devices=rows, corporateLocationsWithoutDevice=no_dev,
               franchiseeLocations=[dict(id=lid, name=names.get(lid, lid)) for lid, reg in regions.items() if reg == "Franchisees"])
    hdr = f" Geotab daily CSVs {out['window']}. Fleet estimate from fleet.config.json (not a confirmed roster)."
    write_ts("fleet.ts", hdr, ts_const("FLEET", out))

