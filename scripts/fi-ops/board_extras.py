SIZE = {"Small Arrangement": "S", "Medium Arrangement": "M", "Large Arrangement": "L"}
def build_uoh(raw, pulled):
    regions, _ = parse_regions()
    recs = [r for f in sorted(glob.glob(os.path.join(raw, "p*.json"))) for r in load_records(f)]
    ids = set(); R = []
    for r in recs:
        if r["Id"] in ids: continue
        ids.add(r["Id"]); R.append(r)
    P = d(pulled); excluded = collections.Counter(); lines = []
    for r in R:
        o = r["Opportunity"]; owner = o["Owner"]["Name"]; lid = LOC_FROM_OWNER(owner)
        if lid == "sao-paulo": continue
        st = o["StageName"]; status = r.get("Opportunity_Product_Status__c"); s = r["Product_Start_Date__c"]
        q = float(r["Quantity"] or 0); u = r.get("u"); u = float(u) if u is not None else None
        if not s or s < "2000-01-01" or d(s) > P: excluded["start date missing, before 2000 or after pull date"] += q; continue
        end = r.get("Product_Lost_Date__c") or r.get("System_Cancelled_Date__c")
        if st == "Closed Won" and status == "Active": known = True
        elif st == "Closed Won":
            known = bool(end)
        else:
            end = end or o.get("Lost_Date__c") or o.get("Last_Stage_Change_Date__c"); known = bool(end)
        if not known: excluded["no end date on a lost/inactive line"] += q; continue
        lines.append(dict(acct=o.get("AccountId") or r["OpportunityId"], loc=lid, s=s, e=end, q=q, u=u, size=SIZE.get((r.get("Product2") or {}).get("Name"), "Other"),
                          cur=r.get("CurrencyIsoCode"), current=(st == "Closed Won" and status == "Active")))
    def snap(D, filt=None):
        Ds = D.isoformat(); acc = collections.defaultdict(float); val = collections.defaultdict(float); units = 0.0; pu = pq = 0.0; lowq = 0.0; pu30 = pq30 = 0.0
        for l in lines:
            if l["s"] <= Ds and (l["e"] is None or l["e"] > Ds) and (filt is None or filt(l)):
                acc[l["acct"]] += l["q"]; units += l["q"]
                if l["u"] is not None:
                    val[l["acct"]] += l["u"] * l["q"]; pu += l["u"] * l["q"]; pq += l["q"]
                    if l["u"] < 30: lowq += l["q"]
                    else: pu30 += l["u"] * l["q"]; pq30 += l["q"]
        n = len(acc)
        return dict(accounts=n, units=round(units), avgUnitPrice=(round(pu / pq, 2) if pq else None), avgUnitPriceExLow=(round(pu30 / pq30, 2) if pq30 else None),
                    avgAccountMonthly=(round(sum(val.values()) / n, 2) if n else None), unitsUnder30=round(lowq), unitsPerAccount=(round(units / n, 2) if n else None))
    years = list(range(2013, P.year))
    hist = [dict(label=f"Dec 31, {y}", date=f"{y}-12-31", **snap(date(y, 12, 31))) for y in years]
    hist.append(dict(label=f"{P.strftime('%b %-d, %Y')} (YTD)", date=P.isoformat(), **snap(P)))
    # by location at year end (units) for a compact matrix
    loc_ids = sorted({l["loc"] for l in lines})
    by_loc = []
    for x in loc_ids:
        row = dict(id=x, region=regions.get(x, "Unassigned"), years={})
        for h in hist:
            sn = snap(d(h["date"]), lambda l, x=x: l["loc"] == x); row["years"][h["date"][:4] if "YTD" not in h["label"] else "YTD"] = dict(accounts=sn["accounts"], units=sn["units"])
        by_loc.append(row)
    # single vs multi, current book (board definition: Closed Won + Active line)
    cur = [l for l in lines if l["current"]]
    acct_units = collections.defaultdict(float)
    for l in cur: acct_units[l["acct"]] += l["q"]
    def bucket(l): return "single" if acct_units[l["acct"]] == 1 else "multi"
    sm = []
    for x in sorted({l["loc"] for l in cur}):
        row = dict(id=x, region=regions.get(x, "Unassigned"), currency=sorted({l["cur"] for l in cur if l["loc"] == x}))
        for b in ("single", "multi"):
            ls = [l for l in cur if l["loc"] == x and bucket(l) == b]
            accts = {l["acct"] for l in ls}; q = sum(l["q"] for l in ls)
            sizes = {}
            for sz in ("S", "M", "L"):
                lz = [l for l in ls if l["size"] == sz and l["u"] is not None]
                qq = sum(l["q"] for l in lz)
                sizes[sz] = dict(units=round(qq), avg=(round(sum(l["u"] * l["q"] for l in lz) / qq, 2) if qq else None))
            pv = [l for l in ls if l["u"] is not None]; pq = sum(l["q"] for l in pv)
            row[b] = dict(accounts=len(accts), units=round(q), avgUnitPrice=(round(sum(l["u"] * l["q"] for l in pv) / pq, 2) if pq else None), sizes=sizes)
        sm.append(row)
    tot = {}
    for b in ("single", "multi"):
        ls = [l for l in cur if bucket(l) == b]; pq = sum(l["q"] for l in ls if l["u"] is not None)
        sizes = {}
        for sz in ("S", "M", "L"):
            lz = [l for l in ls if l["size"] == sz and l["u"] is not None]; qq = sum(l["q"] for l in lz)
            sizes[sz] = dict(units=round(qq), avg=(round(sum(l["u"] * l["q"] for l in lz) / qq, 2) if qq else None))
        tot[b] = dict(accounts=len({l["acct"] for l in ls}), units=round(sum(l["q"] for l in ls)), avgUnitPrice=(round(sum(l["u"] * l["q"] for l in ls if l["u"] is not None) / pq, 2) if pq else None), sizes=sizes)
    out = dict(pulled=pulled, lineItems=len(R), linesUsed=len(lines), excludedUnits={k: round(v) for k, v in excluded.items()},
               currentBookUnits=round(sum(l["q"] for l in cur)), currentBookAccounts=len(acct_units),
               history=hist, byLocation=by_loc, singleMulti=sm, singleMultiTotal=tot, priceBook=dict(S=60, M=70, L=80))
    hdr = (f" OpportunityLineItem rows pulled {pulled} from {raw} ({len(R)} rows, São Paulo excluded in the query).\n"
           " A unit is on hire at date D if Product_Start_Date__c <= D and its end date is empty or after D.\n"
           " End date = Product_Lost_Date__c, else System_Cancelled_Date__c; for non-Closed-Won stages also Opportunity Lost_Date__c, else Last_Stage_Change_Date__c.\n"
           " Prices are row-level convertCurrency(UnitPrice) (USD), never SOQL SUM aggregates.")
    write_ts("uoh-history.ts", hdr, ts_const("UOH_HISTORY", out))

