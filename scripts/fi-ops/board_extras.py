def build_activity(day, raw):
    cfg = json.load(open(os.path.join(DATA, "people.config.json")))
    excl = set(cfg["excludeLocations"]); hol = set(cfg["holidays"])
    locs, sf_pulled = parse_ops(); regions, _ = parse_regions()
    locs = [l for l in locs if l["id"] not in excl]
    L = {l["id"]: l for l in locs}
    D, ms, ws, ps = periods(day)
    me = ms.replace(day=calendar.monthrange(ms.year, ms.month)[1])
    wd = dict(day=workdays(D, D, hol), week=workdays(ws, D, hol), month=workdays(ms, D, hol), monthTotal=workdays(ms, me, hol))
    missing = [n for n in ACT_NAMES if not find_raw(raw, n)]
    R = {n: (load_records(find_raw(raw, n)) if find_raw(raw, n) else []) for n in ACT_NAMES}
    def inp(s, per):
        if not s: return False
        x = d(s[:10])
        return x == D if per == "day" else (ws <= x <= D if per == "week" else ms <= x <= D)
    PER = ["day", "week", "month"]
    def lid(o): return LOC_FROM_OWNER(o)
    def agg(name, keyf, valk="n"):
        out = collections.defaultdict(lambda: {p: 0.0 for p in PER})
        for r in R[name]:
            if lid(r.get("owner")) in excl: continue
            k = keyf(r)
            if k is None: continue
            for p in PER:
                if inp(r.get("d"), p): out[k][p] += float(r.get(valk) or 0)
        return out
    # per sales name / per login / per location
    trials_sp = agg("trials", lambda r: r.get("sp")); trials_loc = agg("trials", lambda r: lid(r["owner"]))
    due_sp = agg("fu_due", lambda r: r.get("sp")); due_loc = agg("fu_due", lambda r: lid(r["owner"]))
    mv_sp = agg("moves", lambda r: r.get("sp")); mv_loc = agg("moves", lambda r: lid(r["owner"]))
    won_sp = agg("won", lambda r: r.get("sp"), "units"); won_loc = agg("won", lambda r: lid(r["owner"]), "units")
    wond_sp = agg("won", lambda r: r.get("sp"), "deals"); wond_loc = agg("won", lambda r: lid(r["owner"]), "deals")
    ref_login = agg("refresh", lambda r: (lid(r["owner"]), r.get("who") or "(blank)"), "units")
    reflogs_login = agg("refresh", lambda r: (lid(r["owner"]), r.get("who") or "(blank)"), "n")
    ref_loc = agg("refresh", lambda r: lid(r["owner"]), "units")
    od_sp = collections.Counter(); od_loc = collections.Counter()
    for r in R["overdue"]:
        if lid(r.get("owner")) in excl: continue
        od_sp[r.get("sp")] += r["n"]; od_loc[lid(r["owner"])] += r["n"]
    cyc = cfg.get("refreshCyclesPerMonth", 1)
    def plan_month(lids): return sum(L[x]["onHire"] for x in lids if x in L) * cyc
    def exp_split(month_total):
        if month_total is None: return None
        per = month_total / wd["monthTotal"] if wd["monthTotal"] else 0
        return {p: round(per * wd[p], 1) for p in PER}
    def metric(exp, act):
        return {p: {"expected": (None if exp is None else exp[p]), "actual": round(act[p], 1)} for p in PER}
    zero = {p: 0.0 for p in PER}
    def sumd(dicts):
        o = {p: 0.0 for p in PER}
        for x in dicts:
            for p in PER: o[p] += x[p]
        return o
    used_logins = set()
    cards = []
    for pp in cfg["people"]:
        if pp["locationId"] in excl: continue
        bd = cfg["bucketDefaults"][pp["bucket"]]
        tpd = pp.get("trialsPerDay", bd["trialsPerDay"])
        share = pp["refreshShare"] if "refreshShare" in pp else bd["refreshShare"]
        planl = pp.get("planLocations", [pp["locationId"]])
        logins = [(x, lg) for x in planl + [pp["locationId"]] for lg in pp["refreshLogins"]]
        logins = list(dict.fromkeys(logins))
        ref_act = sumd([ref_login[k] for k in logins if k in ref_login]); used_logins.update(k for k in logins if k in ref_login)
        has_ref = bool(pp["refreshLogins"]) or (share not in (None, 0))
        ref_exp = None if share in (None,) else exp_split(plan_month(planl) * share)
        if share == 0 and not pp["refreshLogins"]: ref_exp = None
        tr = sumd([trials_sp[n] for n in pp["salesNames"] if n in trials_sp])
        fu_exp = sumd([due_sp[n] for n in pp["salesNames"] if n in due_sp])
        fu_act = sumd([mv_sp[n] for n in pp["salesNames"] if n in mv_sp])
        wu = sumd([won_sp[n] for n in pp["salesNames"] if n in won_sp]); wdl = sumd([wond_sp[n] for n in pp["salesNames"] if n in wond_sp])
        cards.append(dict(
            id=pp["id"], kind="rep", name=pp["name"], locationId=pp["locationId"], locationName=L.get(pp["locationId"], {}).get("name", pp["locationId"]),
            region=regions.get(pp["locationId"], "Unassigned"), bucket=pp["bucket"], bucketSource=pp["bucketSource"],
            trialsPerDay=tpd, refreshShare=share, planUnitsMonth=(None if ref_exp is None else round(plan_month(planl) * share)),
            refresh=(metric(ref_exp, ref_act) if (has_ref or ref_exp) else None),
            trials=(metric({p: tpd * wd[p] for p in PER}, tr) if (pp["salesNames"] and (tpd or tr["month"])) else None),
            followups=(metric(fu_exp, fu_act) if pp["salesNames"] else None),
            overdue=sum(od_sp[n] for n in pp["salesNames"]), wonUnitsMonth=wu["month"], wonDealsMonth=wdl["month"],
            note=pp.get("note")))
    for fr in cfg["franchisees"]:
        x = fr["locationId"]
        if x in excl or x not in L: continue
        bd = cfg["bucketDefaults"]["franchisee"]
        for k in ref_login:
            if k[0] == x: used_logins.add(k)
        cards.append(dict(
            id=f"fr-{x}", kind="franchisee", name=L[x]["name"] + (f" · {fr['owner']}" if fr.get("owner") else ""), locationId=x, locationName=L[x]["name"],
            region=regions.get(x, "Unassigned"), bucket="franchisee", bucketSource="location (all Salesforce activity under the franchise owner)",
            trialsPerDay=bd["trialsPerDay"], refreshShare=1, planUnitsMonth=plan_month([x]),
            refresh=metric(exp_split(plan_month([x])), ref_loc.get(x, zero)),
            trials=metric({p: bd["trialsPerDay"] * wd[p] for p in PER}, trials_loc.get(x, zero)),
            followups=metric(due_loc.get(x, zero), mv_loc.get(x, zero)),
            overdue=od_loc.get(x, 0), wonUnitsMonth=won_loc.get(x, zero)["month"], wonDealsMonth=wond_loc.get(x, zero)["month"], note=None))
    # refresh plan view per location
    weeks = []
    x = ms
    while x <= D:
        we = min(x + timedelta(days=6 - x.weekday()), me); weeks.append((x, min(we, D), we)); x = we + timedelta(days=1)
    ref_rows_day = collections.defaultdict(float)
    for r in R["refresh"]:
        if lid(r.get("owner")) in excl or not r.get("d"): continue
        ref_rows_day[(lid(r["owner"]), r["d"][:10])] += float(r.get("units") or 0)
    plan_rows = []
    for l in sorted(locs, key=lambda l: -l["onHire"]):
        x = l["id"]; plan = l["onHire"] * cyc
        per = plan / wd["monthTotal"] if wd["monthTotal"] else 0
        act = ref_loc.get(x, zero)["month"]; exp_td = per * wd["month"]
        wk = []
        for a, b, full_end in weeks:
            wa = sum(v for (lx, dd), v in ref_rows_day.items() if lx == x and a.isoformat() <= dd <= b.isoformat())
            wk.append(dict(label=f"{a.strftime('%b')} {a.day}–{full_end.day}", expected=round(per * workdays(a, b, hol), 1), actual=wa, partial=b < full_end))
        lg = sorted([(k[1], v["month"], reflogs_login[k]["month"]) for k, v in ref_login.items() if k[0] == x and v["month"]], key=lambda t: -t[1])
        plan_rows.append(dict(id=x, name=l["name"], region=regions.get(x, "Unassigned"), plan=plan, expectedToDate=round(exp_td, 1), actual=act,
                              pctPlan=(round(100 * act / plan, 1) if plan else None), pctExpected=(round(100 * act / exp_td, 1) if exp_td else None),
                              weeks=wk, logins=[dict(login=a, units=b, logs=c) for a, b, c in lg],
                              routeMtdCustomers=l["routeMtdCustomers"], routeMtdUnits=l["routeMtdUnits"]))
    unattributed = sorted([dict(locationId=k[0], login=k[1], units=v["month"]) for k, v in ref_login.items() if k not in used_logins and v["month"]], key=lambda r: -r["units"])
    # data checks: compare RouteMap MTD with Salesforce refresh logins
    checks = []
    for l in locs:
        x = l["id"]; sfu = ref_loc.get(x, zero)["month"]; rmu = l["routeMtdUnits"]
        logins = {k[1]: (v["month"], reflogs_login[k]["month"]) for k, v in ref_login.items() if k[0] == x}
        match = [lg for lg, (u, n) in logins.items() if rmu and u == rmu and (l["routeMtdCustomers"] in (None, n))]
        if rmu is None: continue
        if sfu and rmu < 0.5 * sfu:
            checks.append(dict(locationId=x, name=l["name"], onHire=l["onHire"], sfRefreshUnits=sfu, routeMtdCustomers=l["routeMtdCustomers"], routeMtdUnits=rmu,
                               matchingLogin=(match[0] if match else None),
                               otherLogins=[dict(login=lg, units=u, logs=n) for lg, (u, n) in sorted(logins.items(), key=lambda t: -t[1][0]) if lg not in match and u]))
    hdr = (f" Coverage day {D.isoformat()} (America/New_York). Week {ws.isoformat()}..{D.isoformat()}, month {ms.isoformat()}..{D.isoformat()}.\n"
           f" Salesforce via user-salesforce-reads soqlQuery; raw dir {raw}. Missing raw: {missing or 'none'}.\n"
           " Targets come from src/data/people.config.json (PLACEHOLDERS until Patrick sets them). São Paulo excluded.")
    out = dict(day=D.isoformat(), dayLabel=D.strftime("%a %b %-d"), weekLabel=f"{ws.strftime('%a %b %-d')}–{D.strftime('%a %b %-d')}",
               monthLabel=f"{ms.strftime('%b %-d')}–{D.strftime('%b %-d, %Y')}", salesforcePulled=sf_pulled, status=("pending" if missing else "ok"), missing=missing,
               workdays=wd, targetsArePlaceholders=cfg["targetsArePlaceholders"], targetsNote=cfg["targetsNote"],
               bucketDefaults=cfg["bucketDefaults"], cards=cards, refreshPlan=plan_rows, unattributedRefresh=unattributed, routeChecks=checks)
    write_ts("activity.ts", hdr, ts_const("ACTIVITY", out))

