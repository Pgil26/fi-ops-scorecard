#!/usr/bin/env python3
"""FI Ops board extras: rep/franchisee report card, refresh-vs-plan, hybrid benchmark,
Geotab coverage, data checks, units-on-hire history.

Subcommands (all write generated TS into src/data/, never touch ops.ts or regions.ts):
  queries  --day D                 print the activity SOQL (JSON name->query) to run via user-salesforce-reads soqlQuery
  activity --day D --raw DIR       build src/data/activity.ts from DIR/act_<name>.(json|txt)
  fleet    --day D                 build src/data/fleet.ts from /workspace/geotab-daily-start-end-local-*.csv
  uoh      --raw DIR --pulled DATE build src/data/uoh-history.ts from DIR/p*.json (OpportunityLineItem pages)
  uoh-query --after ID             print the line-item page SOQL (2000 rows, Id > ID)
Rules: never invent numbers; a missing raw file makes that section 'pending' (no older day reused).
"""
import argparse, calendar, collections, csv, glob, json, os, re, sys
from datetime import date, timedelta

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DATA = os.path.join(REPO, "src", "data")
ACT_NAMES = ["trials", "refresh", "fu_due", "moves", "overdue", "won"]

# ---------- helpers ----------
def d(s): return date.fromisoformat(s)

def load_records(path):
    t = open(path).read()
    if path.endswith(".json"):
        try:
            v = json.loads(t)
            if isinstance(v, list): return v
            if isinstance(v, dict) and "records" in v: return v["records"]
        except Exception: pass
    m = re.search(r"Full text: (\S+?\.txt)", t)
    if m and os.path.exists(m.group(1)): t = open(m.group(1)).read()
    i = t.index('{"totalSize"'); j = t.rindex("}")
    return json.loads(t[i:j + 1])["records"]

def find_raw(raw, name):
    for ext in (".json", ".txt"):
        p = os.path.join(raw, f"act_{name}{ext}")
        if os.path.exists(p): return p
    return None

def ts_const(name, value, typ="any"):
    return f"export const {name}: {typ} = {json.dumps(value, indent=1, ensure_ascii=False)};\n"

def write_ts(fname, header, body):
    p = os.path.join(DATA, fname)
    open(p, "w").write(f"/* GENERATED by scripts/fi-ops/board_extras.py — do not edit by hand.\n{header}\n*/\n/* eslint-disable */\n" + body)
    print("wrote", p)

def parse_ops():
    """Read LOCATIONS from ops.ts (written by the daily digest build)."""
    src = open(os.path.join(DATA, "ops.ts")).read()
    block = src.split("export const LOCATIONS")[1].split("export const VANS")[0]
    rows = []
    for m in re.finditer(r"\{ id: \"([a-z-]+)\", name: \"([^\"]+)\",(.*?)\},\n", block):
        body = m.group(3)
        def g(k):
            mm = re.search(rf"\b{k}: (null|-?[0-9.]+)", body)
            return None if (not mm or mm.group(1) == "null") else float(mm.group(1))
        rows.append(dict(id=m.group(1), name=m.group(2), onHire=int(g("totalUnits") - g("inactive")),
                         sfMtdUnits=g("sfMtdUnits"), sfMtdRows=g("sfMtdRows"),
                         routeMtdCustomers=g("routeMtdCustomers"), routeMtdUnits=g("routeMtdUnits")))
    pulled = re.search(r'sales: "([^"]+)"', src).group(1)
    return rows, pulled

def parse_regions():
    src = open(os.path.join(DATA, "regions.ts")).read()
    regions = {}
    for m in re.finditer(r'\{ id: "([a-z]+)", name: "([^"]+)", locations: \[([^\]]*)\]', src):
        for lid in re.findall(r'"([a-z-]+)"', m.group(3)): regions[lid] = m.group(2)
    vl = src.split("export const VAN_LOCATIONS")[1].split("};")[0]
    van_locs = dict(re.findall(r"(\w+): \"([a-z-]+)\"", vl))
    return regions, van_locs

def norm(s): return re.sub(r"[^a-z0-9]", "", s.lower())

LOC_FROM_OWNER = lambda o: (o or "").replace(" FI", "").replace("New Jersey South", "New Jersey").strip().lower().replace(" ", "-")

def workdays(a, b, hol):
    """Mon–Fri working days in [a, b] excluding holidays."""
    n = 0; x = a
    while x <= b:
        if x.weekday() < 5 and x.isoformat() not in hol: n += 1
        x += timedelta(days=1)
    return n

# ---------- queries ----------
def periods(day):
    D = d(day); ms = D.replace(day=1); ws = D - timedelta(days=D.weekday())
    return D, ms, ws, min(ms, ws)

def activity_queries(day):
    D, ms, ws, ps = periods(day); a, b = ps.isoformat(), D.isoformat()
    return {
        "trials": f"SELECT Owner.Name owner, Sales_Person_Contact__r.Name sp, Trial_Date__c d, COUNT(Id) n FROM Lead WHERE Trial_Date__c >= {a} AND Trial_Date__c <= {b} GROUP BY Owner.Name, Sales_Person_Contact__r.Name, Trial_Date__c",
        "refresh": f"SELECT Opportunity__r.Owner.Name owner, Refresh_Done_By__c who, Refresh_Date_Formula__c d, COUNT(Id) n, SUM(Refresh_Units__c) units FROM Product_Refresh__c WHERE Refresh_Date_Formula__c >= {a} AND Refresh_Date_Formula__c <= {b} GROUP BY Opportunity__r.Owner.Name, Refresh_Done_By__c, Refresh_Date_Formula__c",
        "fu_due": f"SELECT Owner.Name owner, Sales_Person_Contact__r.Name sp, Follow_up_Date__c d, COUNT(Id) n FROM Lead WHERE Follow_up_Date__c >= {a} AND Follow_up_Date__c <= {b} GROUP BY Owner.Name, Sales_Person_Contact__r.Name, Follow_up_Date__c",
        "moves": f"SELECT Owner.Name owner, Sales_Person_Contact__r.Name sp, Status, Last_Stage_Change_Date__c d, COUNT(Id) n FROM Lead WHERE Last_Stage_Change_Date__c >= {a} AND Last_Stage_Change_Date__c <= {b} AND Status != 'Trial' GROUP BY Owner.Name, Sales_Person_Contact__r.Name, Status, Last_Stage_Change_Date__c",
        "overdue": f"SELECT Owner.Name owner, Sales_Person_Contact__r.Name sp, Status, COUNT(Id) n FROM Lead WHERE IsConverted = false AND Follow_up_Date__c <= {b} AND Status NOT IN ('Unqualified','Did Not Accept Trial') GROUP BY Owner.Name, Sales_Person_Contact__r.Name, Status",
        "won": f"SELECT Opportunity.Owner.Name owner, Opportunity.Sales_Person_Contact__r.Name sp, Product_Start_Date__c d, COUNT_DISTINCT(OpportunityId) deals, SUM(Quantity) units FROM OpportunityLineItem WHERE Opportunity.StageName = 'Closed Won' AND Product_Start_Date__c >= {a} AND Product_Start_Date__c <= {b} GROUP BY Opportunity.Owner.Name, Opportunity.Sales_Person_Contact__r.Name, Product_Start_Date__c",
    }

UOH_FIELDS = "Id, OpportunityId, Opportunity.AccountId, Opportunity.Owner.Name, Opportunity.StageName, Opportunity.Lost_Date__c, Opportunity.Last_Stage_Change_Date__c, Product2.Name, Quantity, convertCurrency(UnitPrice) u, CurrencyIsoCode, Product_Start_Date__c, Product_Lost_Date__c, System_Cancelled_Date__c, Opportunity_Product_Status__c"
def uoh_query(after=None):
    w = "Product_Start_Date__c != null AND Opportunity.Owner.Name != 'Sao Paulo FI'"
    if after: w += f" AND Id > '{after}'"
    return f"SELECT {UOH_FIELDS} FROM OpportunityLineItem WHERE {w} ORDER BY Id LIMIT 2000"

